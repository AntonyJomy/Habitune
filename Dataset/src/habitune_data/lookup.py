"""Backend-ready location resolution helpers for Map View 1."""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path

from .ala import ALAClient, ALAError, facet_map
from .cleaning import family_filter, name_key
from .config import BIRD_FILTERS, BIRD_QUERY, INSECT_FILTERS, INSECT_QUERY
from .geometry import find_area
from .street import MAX_ASSIGNMENT_DISTANCE_M, distance_m


COORDINATE_PATTERN = re.compile(
    r"^\s*(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)\s*$"
)


def load_contract(processed_dir: Path) -> dict:
    """Load the compact city/suburb contract generated by the build pipeline."""

    return json.loads((processed_dir / "map_view1.json").read_text(encoding="utf-8"))


def load_boundaries(processed_dir: Path) -> list[dict]:
    """Load supported suburb polygons used for coordinate resolution."""

    data = json.loads((processed_dir / "suburb_boundaries.geojson").read_text(encoding="utf-8"))
    return data["features"]


def resolve_coordinates(latitude: float, longitude: float, processed_dir: Path) -> str | None:
    """Resolve a WGS84 point to a supported Map View 1 suburb."""

    return find_area(longitude, latitude, load_boundaries(processed_dir))


def search_addresses(query: str, processed_dir: Path, limit: int = 10) -> list[dict]:
    """Return deterministic exact/prefix/contains matches from the address export."""

    query_key = name_key(query)
    if not query_key:
        return []
    # Exact matches come first, followed by prefix and contains matches.
    ranked = []
    with (processed_dir / "address_lookup.csv").open(encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream):
            candidate = row["search_key"]
            if candidate == query_key:
                rank = 0
            elif candidate.startswith(query_key):
                rank = 1
            elif query_key in candidate:
                rank = 2
            else:
                continue
            ranked.append((rank, len(candidate), row["address"], row))
    ranked.sort(key=lambda item: item[:3])
    return [item[3] for item in ranked[:limit]]


def nearest_address(
    latitude: float,
    longitude: float,
    processed_dir: Path,
    max_distance_m: float = MAX_ASSIGNMENT_DISTANCE_M,
    suburb: str | None = None,
) -> dict | None:
    """Return the nearest address, optionally limited to one resolved suburb."""

    # Coordinates use the nearest known address to identify a street.
    best = None
    best_distance = max_distance_m
    with (processed_dir / "address_lookup.csv").open(encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream):
            if suburb and name_key(row["suburb"]) != name_key(suburb):
                continue
            candidate_distance = distance_m(
                longitude,
                latitude,
                float(row["longitude"]),
                float(row["latitude"]),
            )
            if candidate_distance <= best_distance:
                best = row
                best_distance = candidate_distance
    if best:
        best = {**best, "distance_from_input_m": round(best_distance, 1)}
    return best


def _street_by_key(processed_dir: Path) -> dict[str, dict]:
    """Index processed street records by their stable street key."""

    payload = json.loads((processed_dir / "street_level.json").read_text(encoding="utf-8"))
    return {street["street_key"]: street for street in payload["streets"]}


def map_view(query: str | None, processed_dir: Path) -> dict:
    """Implement the agreed input/no-input behavior for downstream services."""

    contract = load_contract(processed_dir)
    # Blank input returns the suburb overview used by the default map.
    if not query or not query.strip():
        return {
            "mode": "suburb_overview",
            "city_summary": contract["city_summary"],
            "suburbs": contract["suburbs"],
        }

    # Coordinate input and text input follow separate lookup paths.
    coordinate_match = COORDINATE_PATTERN.fullmatch(query)
    candidates = []
    if coordinate_match:
        latitude, longitude = map(float, coordinate_match.groups())
        suburb = resolve_coordinates(latitude, longitude, processed_dir)
        selected_address = (
            nearest_address(latitude, longitude, processed_dir, suburb=suburb)
            if suburb
            else None
        )
    else:
        candidates = search_addresses(query, processed_dir)
        exact = [row for row in candidates if row["search_key"] == name_key(query)]
        selected_address = exact[0] if exact else candidates[0] if len(candidates) == 1 else None
        if candidates and not selected_address:
            return {
                "mode": "address_candidates",
                "query": query,
                "message": "More than one address matched. Select a full address.",
                "address_candidates": candidates,
            }
        suburb = selected_address["suburb"] if selected_address else None
        latitude = float(selected_address["latitude"]) if selected_address else None
        longitude = float(selected_address["longitude"]) if selected_address else None

    # Do not guess a location when the input cannot be resolved safely.
    if not suburb or not selected_address:
        return {
            "mode": "not_found",
            "query": query,
            "message": (
                "Location is outside the 11 supported areas, did not match an address, "
                "or has no street address within 250 metres."
            ),
            "address_candidates": candidates,
        }
    suburb_metrics = next(item for item in contract["suburbs"] if item["suburb"] == suburb)
    street = _street_by_key(processed_dir).get(selected_address["street_key"])
    if not street:
        return {
            "mode": "not_found",
            "query": query,
            "message": "The address resolved, but its street aggregate is missing.",
            "address_candidates": candidates,
        }
    # Street assets are returned with the parent suburb kept as context.
    return {
        "mode": "street_level",
        "query": query,
        "resolved_location": {
            "latitude": latitude,
            "longitude": longitude,
            "matched_address": selected_address["address"],
            "distance_to_address_m": selected_address.get("distance_from_input_m", 0.0),
            "input_type": "coordinates" if coordinate_match else "matched_address",
        },
        "resolved_suburb": suburb,
        "resolved_street": {
            "street_key": street["street_key"],
            "street_id": street["street_id"],
            "street_name": street["street_name"],
        },
        "street_data": {
            **street,
            "animals_near_location": {
                "label": "Animals near your location",
                "radius_m": 250,
                "birds": {"status": "live_ala_query_required"},
                "pollinator_insects": {"status": "live_ala_query_required"},
            },
            "evidence_note": (
                "Local assets are assigned to the nearest address within 250 m. "
                "Birds and pollinator-insect candidates are ALA occurrence observations "
                "queried within the requested radius, not confirmed habitat or abundance."
            ),
        },
        "suburb_context": suburb_metrics,
        "address_candidates": candidates,
    }


def _nearby_birds(
    client: ALAClient,
    root: Path,
    latitude: float,
    longitude: float,
    radius_m: int,
) -> dict:
    """Query and filter bird observations around one location."""

    try:
        payload = client.search(
            q=BIRD_QUERY,
            filters=BIRD_FILTERS,
            facets=("species",),
            latitude=latitude,
            longitude=longitude,
            radius_km=radius_m / 1000,
            page_size=0,
        )
    except ALAError as error:
        return {"status": "unavailable", "reason": str(error)}

    relevant = {}
    with (root / "processed" / "relevant_birds.csv").open(
        encoding="utf-8", newline=""
    ) as stream:
        for row in csv.DictReader(stream):
            relevant[row["scientific_name"]] = row
    birds = []
    for scientific_name, occurrence_count in sorted(facet_map(payload, "species").items()):
        trait = relevant.get(scientific_name)
        if not trait:
            continue
        birds.append(
            {
                "scientific_name": scientific_name,
                "common_name": trait["common_name"],
                "feeding_guild": trait["feeding_guild"],
                "occurrence_count": occurrence_count,
                "role_pollination": trait["role_pollination"] == "True",
                "role_seed_dispersal": trait["role_seed_dispersal"] == "True",
                "role_insect_food_web": trait["role_insect_food_web"] == "True",
            }
        )
    return {
        "status": "ok",
        "species_count": len(birds),
        "filtered_occurrence_count": sum(row["occurrence_count"] for row in birds),
        "all_bird_occurrence_count": int(payload.get("totalRecords", 0)),
        "species": birds,
        "filter": "nectar or fruit diet percentage greater than zero",
    }


def _nearby_pollinator_insects(
    client: ALAClient,
    root: Path,
    latitude: float,
    longitude: float,
    radius_m: int,
) -> dict:
    """Query insect observations and retain prevalidated candidate species."""

    candidates = {}
    families = set()
    with (root / "processed" / "pollinator_insect_taxa.csv").open(
        encoding="utf-8", newline=""
    ) as stream:
        for row in csv.DictReader(stream):
            candidates[row["scientific_name"]] = row
            if row["family"]:
                families.add(row["family"])
    filters = INSECT_FILTERS + (family_filter(sorted(families)),)
    try:
        payload = client.search(
            q=INSECT_QUERY,
            filters=filters,
            facets=("species",),
            latitude=latitude,
            longitude=longitude,
            radius_km=radius_m / 1000,
            page_size=0,
        )
    except ALAError as error:
        return {"status": "unavailable", "reason": str(error)}

    insects = []
    for scientific_name, occurrence_count in sorted(facet_map(payload, "species").items()):
        evidence = candidates.get(scientific_name)
        if not evidence:
            continue
        insects.append(
            {
                "scientific_name": scientific_name,
                "family": evidence["family"],
                "order": evidence["order"],
                "occurrence_count": occurrence_count,
                "evidence_level": evidence["evidence_level"],
                "exact_local_species_evidence": (
                    evidence["exact_local_species_evidence"] == "True"
                ),
            }
        )
    return {
        "status": "ok",
        "species_count": len(insects),
        "filtered_occurrence_count": sum(row["occurrence_count"] for row in insects),
        "all_candidate_family_occurrence_count": int(payload.get("totalRecords", 0)),
        "species": insects,
        "filter": "evidence-filtered pollinator candidate species",
    }


def enrich_location_animals(
    result: dict,
    root: Path,
    *,
    radius_m: int = 250,
    offline: bool = False,
) -> dict:
    """Add birds and pollinator insects around the same resolved location."""

    if result.get("mode") != "street_level":
        return result
    location = result["resolved_location"]
    client = ALAClient(root / "cache" / "ala", offline=offline)
    latitude = float(location["latitude"])
    longitude = float(location["longitude"])
    result["street_data"]["animals_near_location"] = {
        "label": "Animals near your location",
        "radius_m": radius_m,
        "centre": {"latitude": latitude, "longitude": longitude},
        "birds": _nearby_birds(client, root, latitude, longitude, radius_m),
        "pollinator_insects": _nearby_pollinator_insects(
            client, root, latitude, longitude, radius_m
        ),
        "evidence_type": "ALA occurrence observations within radius",
    }
    return result


def enrich_street_birds(
    result: dict,
    root: Path,
    *,
    radius_m: int = 250,
    offline: bool = False,
) -> dict:
    """Backward-compatible wrapper for the unified animal enrichment."""

    return enrich_location_animals(result, root, radius_m=radius_m, offline=offline)
